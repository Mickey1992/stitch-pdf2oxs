package common.entity;

public class ChartInfo {
    private String chartNo;
    private String chartName;
    private String designedBy;
    private String brandName;
    private String copyright;
    private int chartWidth;
    private int chartHeight;
    private String fabricCount;
    private String fabricWidth;
    private String fabricHeight;
    private int numberOfColors;

    public String getChartNo() {
        return chartNo;
    }

    public void setChartNo(String chartNo) {
        this.chartNo = chartNo;
    }

    public String getChartName() {
        return chartName;
    }

    public void setChartName(String chartName) {
        this.chartName = chartName;
    }

    public String getDesignedBy() {
        return designedBy;
    }

    public void setDesignedBy(String designedBy) {
        this.designedBy = designedBy;
    }

    public String getBrandName() {
        return brandName;
    }

    public void setBrandName(String brandName) {
        this.brandName = brandName;
    }

    public String getCopyright() {
        return copyright;
    }

    public void setCopyright(String copyright) {
        this.copyright = copyright;
    }

    public int getChartWidth() {
        return chartWidth;
    }

    public void setChartWidth(int chartWidth) {
        this.chartWidth = chartWidth;
    }

    public int getChartHeight() {
        return chartHeight;
    }

    public void setChartHeight(int chartHeight) {
        this.chartHeight = chartHeight;
    }

    public String getFabricCount() {
        return fabricCount;
    }

    public void setFabricCount(String fabricCount) {
        this.fabricCount = fabricCount;
    }

    public String getFabricWidth() {
        return fabricWidth;
    }

    public void setFabricWidth(String fabricWidth) {
        this.fabricWidth = fabricWidth;
    }

    public String getFabricHeight() {
        return fabricHeight;
    }

    public void setFabricHeight(String fabricHeight) {
        this.fabricHeight = fabricHeight;
    }

    public int getNumberOfColors() {
        return numberOfColors;
    }

    public void setNumberOfColors(int numberOfColors) {
        this.numberOfColors = numberOfColors;
    }
}
